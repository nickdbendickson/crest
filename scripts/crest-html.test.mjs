// Crest.html (repo root) is the one-file desk: the same src/ desk and engine as the web and desktop apps, inlined by
// `npm run build:crest-html`. Fail `npm test` when it is older than its sources.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";

const repo = fileURLToPath(new URL("..", import.meta.url));
const html = readFileSync(join(repo, "Crest.html"), "utf8");

describe("Crest.html", () => {
  it("is built from the current sources (else run `npm run build:crest-html` and commit)", () => {
    const m = html.match(/^<!--[^\n]*\ncrest-build-info (\{[\s\S]*?\})\n-->/);
    assert.ok(m, "no crest-build-info header: Crest.html was not generated by build:crest-html");
    const info = JSON.parse(m[1]);
    assert.ok(info.sources["src/lib/crest/engine.ts"] && info.sources["src/components/crest/desk.tsx"]);
    const stale = Object.entries(info.sources).filter(([rel, digest]) => {
      const file = join(repo, rel);
      if (!existsSync(file)) return true;
      const text = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
      return createHash("sha256").update(text).digest("hex") !== digest;
    });
    assert.deepEqual(stale.map(([rel]) => rel), []);
  });

  it("is one file: nothing loaded from ./assets or a CDN", () => {
    assert.doesNotMatch(html, /(?:src|href)="\.\/assets\//);
    assert.doesNotMatch(html, /(?:src|href)="(?:https?:)?\/\/(?:unpkg|cdn|cdnjs|jsdelivr)/);
    assert.match(html, /<script type="module">/);
    assert.doesNotMatch(html, /__VITE_PRELOAD__/, "unreplaced Vite placeholder: the lazy map would throw");
    assert.match(html, /<link rel="icon"[^>]*href="data:image\/svg\+xml/);
  });

  it("can reach the BLM PLSS service (no Content-Security-Policy; service URL inlined)", () => {
    assert.doesNotMatch(html, /Content-Security-Policy/i);
    assert.ok(html.includes("https://gis.blm.gov/arcgis/rest/services/Cadastral/BLM_Natl_PLSS_CadNSDI/MapServer"));
  });

  it("can reach the ND NG911 address point service (URL inlined)", () => {
    assert.ok(html.includes("https://services1.arcgis.com/GOcSXpzwBHyk2nog/arcgis/rest/services/NDGISHUBSiteStructureAddressPoints/FeatureServer/0"));
  });

  it("can reach the USGS 3DEP terrain service for the terrain outline (URL inlined)", () => {
    assert.ok(html.includes("https://elevation.nationalmap.gov/arcgis/rest/services/3DEPElevation/ImageServer"));
  });
});
